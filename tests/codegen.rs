/// Must be kept in sync with `JoiningType` in `src/unicode.rs`
const JOINING_TYPES: [(&str, &str); 6] = [
    ("U", "Non_Joining"),
    ("C", "Join_Causing"),
    ("D", "Dual_Joining"),
    ("L", "Left_Joining"),
    ("R", "Right_Joining"),
    ("T", "Transparent"),
];

const CODE_POINTS: usize = 0x11_0000;
const THIRD_BITS: u32 = 3;
const SECOND_BITS: u32 = 5;

const PAYLOAD_MASK: u32 = (1 << 21) - 1;
const POOL_OFFSET_BITS: u32 = 16;
const KIND_SHIFT: u32 = 21;
const CCC_SHIFT: u32 = 24;

const JOINING_TYPE_SHIFT: u32 = 5;
const MARK_SHIFT: u32 = 8;

const HANGUL_S_BASE: u32 = 0xac00;
const HANGUL_L_BASE: u32 = 0x1100;
const HANGUL_V_BASE: u32 = 0x1161;
const HANGUL_T_BASE: u32 = 0x11a7;
const HANGUL_L_COUNT: u32 = 19;
const HANGUL_V_COUNT: u32 = 21;
const HANGUL_T_COUNT: u32 = 28;
const HANGUL_N_COUNT: u32 = HANGUL_V_COUNT * HANGUL_T_COUNT;
const HANGUL_S_COUNT: u32 = HANGUL_L_COUNT * HANGUL_N_COUNT;
